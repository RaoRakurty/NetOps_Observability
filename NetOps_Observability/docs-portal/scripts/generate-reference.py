# ─────────────────────────────── API reference ──────────────────────────────

ROUTE_RE = re.compile(
    r'\{"(GET|POST|PUT|PATCH|DELETE)",\s*"([^"]+)",\s*"([^"]+)",\s*'
    r'((?:"(?:[^"\\]|\\.)*"\s*\+?\s*)+)\}',
    re.S,
)
STRING_RE = re.compile(r'"((?:[^"\\]|\\.)*)"')


def go_strings(chunk: str) -> str:
    """Join a Go concatenated-string literal into one Python string."""
    parts = [m.group(1) for m in STRING_RE.finditer(chunk)]
    return "".join(parts).replace('\\"', '"').replace("\\\\", "\\")


def read_routes() -> list[tuple[str, str, str, str]]:
    src = OPENAPI.read_text(encoding="utf-8")
    start = src.index("var apiRoutes")
    end = src.index("\n}\n", start)
    body = src[start:end]
    routes = []
    for m in ROUTE_RE.finditer(body):
        routes.append((m.group(1), m.group(2), m.group(3), go_strings(m.group(4))))
    if not routes:
        sys.exit("no routes parsed out of openapi.go — the literal shape changed")
    return routes


def md_cell(text: str) -> str:
    """One table cell, safe for MDX.

    Docusaurus parses Markdown through MDX, which reads a bare `{...}` as a
    JavaScript expression. Alert summaries carry `{{ $value }}` and route
    summaries carry `{framework_id, enabled}`, so braces and angle brackets
    OUTSIDE inline code are escaped to HTML entities. Braces inside backticks are left alone: MDX does
    not parse expressions there, and escaping them would print the entity.
    """
    text = text.replace("|", "\\|").replace("\n", " ").strip()
    out, in_code = [], False
    for ch in text:
        if ch == "`":
            in_code = not in_code
            out.append(ch)
        elif ch == "{" and not in_code:
            out.append("&#123;")
        elif ch == "}" and not in_code:
            out.append("&#125;")
        elif ch == "<" and not in_code:
            # MDX reads a bare `<` as the start of a JSX tag, and rule
            # expressions carry things like `z<-3`.
            out.append("&lt;")
        elif ch == ">" and not in_code:
            out.append("&gt;")
        else:
            out.append(ch)
    return "".join(out)


def gen_api(routes) -> str:
    by_tag: dict[str, list] = {}
    for method, path, tag, summary in routes:
        by_tag.setdefault(tag, []).append((method, path, summary))

    out = ["---", "title: REST API reference",
           "description: Every documented operation on the Correlix REST API, "
           "generated from the same route table the server publishes at "
           "/api/openapi.json.",
           "page_type: reference",
           "sidebar_position: 20", "---", "", BANNER, "",
           "# REST API reference", "",
           f"Correlix publishes {len(routes)} documented operations across "
           f"{len(by_tag)} groups. The table below is generated from the route "
           "table the server itself serves, so it cannot drift from the running "
           "API.", "",
           "Fetch the machine-readable document from your own deployment:", "",
           "```bash",
           'curl -s -H "Authorization: Bearer $TOKEN" \\',
           "  http://localhost:8000/api/openapi.json",
           "```", "",
           "## Authentication", "",
           "Every operation takes one of two credentials in the "
           "`Authorization` header:", "",
           "| Credential | Header | Obtained from |",
           "|---|---|---|",
           "| Access token (JWT) | `Authorization: Bearer <jwt>` | "
           "`POST /api/auth/login` |",
           "| API key | `Authorization: Bearer ntk_…` or `X-API-Key: ntk_…` | "
           "**Administration → API Access** |", "",
           "A request without a credential is refused with `401` and the body "
           "`{\"error\":\"missing bearer token\"}`.", ""]

    for tag in sorted(by_tag):
        out += [f"## {tag}", "", "| Method | Path | What it does |", "|---|---|---|"]
        for method, path, summary in sorted(by_tag[tag], key=lambda r: (r[1], r[0])):
            out.append(f"| `{method}` | `{md_cell(path)}` | {md_cell(summary)} |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


# ────────────────────────────── Feature flags ───────────────────────────────

FLAG_READ_RE = re.compile(
    r'(?:os\.Getenv|envBool)\("((?:FEATURE|ENABLE)_[A-Z_0-9]+)"\)')
FLAG_CONST_RE = re.compile(
    r'Env\w*\s*=\s*"((?:FEATURE|ENABLE)_[A-Z_0-9]+)"')


def read_flags() -> list[str]:
    found: set[str] = set()
    for path in BACKEND.rglob("*.go"):
        if path.name.endswith("_test.go"):
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        found.update(FLAG_READ_RE.findall(text))
        found.update(FLAG_CONST_RE.findall(text))
    return sorted(found)


def compose_defaults() -> dict[str, str]:
    text = COMPOSE.read_text(encoding="utf-8", errors="replace")
    out: dict[str, str] = {}
    for m in re.finditer(
            r'^\s+((?:FEATURE|ENABLE)_[A-Z_0-9]+):\s*\$\{[A-Z_0-9]+:-([^}]*)\}',
            text, re.M):
        out.setdefault(m.group(1), m.group(2) or "(empty)")
    return out


