           "- A flag is read as the exact string `true`. Any other value, "
           "including `TRUE` and `1`, leaves the feature off.",
           "- An optional MODULE whose flag is off registers no routes at "
           "all, so its API paths answer `404` and the feature is not "
           "enumerable from outside. This holds for the security lane, "
           "configuration backup, packet capture, the BMP receiver and the "
