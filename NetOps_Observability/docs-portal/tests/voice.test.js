// A task page's description is its abstract, and it obeys the same grammar as
// the title: an imperative verb, then the benefit. Palo Alto keys the DITA
// shortdesc to the topic type this way, and it is why their guides scan.
test('task-page descriptions start with an imperative verb', () => {
  const hits = [];
  for (const page of PAGES) {
    if (page.front.page_type !== 'task') continue;
    const first = (page.front.description || '').split(/\s+/)[0].replace(/[^A-Za-z]/g, '');
    if (!TASK_VERBS.includes(first)) {
      hits.push({ rel: page.rel, line: 1, detail: `description starts "${first}" — use an imperative verb` });
    }
  }
  assert.equal(hits.length, 0, report(hits, 'task descriptions that do not lead with a verb'));
});

test('task pages are titled with a verb and follow Before you begin / Steps / Result / Related', () => {
  const hits = [];
  for (const page of PAGES) {
    if (page.front.page_type !== 'task') continue;
    const first = (page.front.title || '').split(/\s+/)[0].replace(/[^A-Za-z]/g, '');
    if (!TASK_VERBS.includes(first)) {
      hits.push({ rel: page.rel, line: 1, detail: `title "${page.front.title}" does not start with a task verb` });
    }
    const heads = [...page.body.matchAll(/^##\s+(.+)$/gm)].map(m => m[1].trim());
    for (const need of ['Before you begin', 'Steps']) {
      if (!heads.includes(need)) hits.push({ rel: page.rel, line: 1, detail: `missing "## ${need}"` });
    }
    if (!heads.includes('Result') && !heads.includes('What you see')) {
      hits.push({ rel: page.rel, line: 1, detail: 'missing "## Result" or "## What you see"' });
    }
    if (!heads.includes('Related')) hits.push({ rel: page.rel, line: 1, detail: 'missing "## Related"' });
    const order = heads.filter(h => ['Before you begin', 'Steps', 'Result', 'What you see', 'Related'].includes(h));
    const rank = { 'Before you begin': 0, 'Steps': 1, 'Result': 2, 'What you see': 2, 'Related': 3 };
    for (let i = 1; i < order.length; i++) {
      if (rank[order[i]] < rank[order[i - 1]]) {
        hits.push({ rel: page.rel, line: 1, detail: `"${order[i]}" comes after "${order[i - 1]}"` });
      }
    }
  }
  assert.equal(hits.length, 0, report(hits, 'task-page structure problems'));
});

// ── 8. concept pages are titled as concepts, not tasks ──────────────────────

test('concept pages are not titled like procedures', () => {
  const hits = [];
  for (const page of PAGES) {
    if (page.front.page_type !== 'concept') continue;
    const first = (page.front.title || '').split(/\s+/)[0].replace(/[^A-Za-z]/g, '');
    if (TASK_VERBS.includes(first)) {
      hits.push({ rel: page.rel, line: 1, detail: `concept page titled "${page.front.title}" — make it a task page or retitle it` });
    }
    const heads = [...page.body.matchAll(/^##\s+(.+)$/gm)].map(m => m[1].trim());
    if (!heads.includes('Related')) hits.push({ rel: page.rel, line: 1, detail: 'missing "## Related"' });
  }
  assert.equal(hits.length, 0, report(hits, 'concept-page problems'));
});

