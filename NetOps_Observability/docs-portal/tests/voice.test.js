// ── 10. internal links resolve ──────────────────────────────────────────────

// Docusaurus builds with onBrokenLinks: 'throw', which catches this too — but a
// failing unit test names the file in a second, and the build takes a minute.
test('every internal link resolves to a page', () => {
  const slugs = new Set();
  for (const page of PAGES) {
    const rel = page.rel.replace(/\.mdx?$/, '');
    slugs.add('/' + rel);
    slugs.add('/' + rel.replace(/\/index$/, ''));
    if (page.front.slug) slugs.add(page.front.slug.replace(/\/$/, '') || '/');
  }
  slugs.add('/');
  const dirs = new Set(PAGES.map(p => '/' + path.dirname(p.rel)));

  const hits = [];
  for (const page of PAGES) {
    for (const m of page.body.matchAll(/\]\((\/[^)#\s]*)(#[^)\s]*)?\)/g)) {
      const target = m[1].replace(/\/$/, '') || '/';
      if (slugs.has(target) || dirs.has(target)) continue;
      hits.push({ rel: page.rel, line: lineOf(page, page.raw.indexOf(m[0])), detail: `dead link ${m[1]}` });
    }
  }
  assert.equal(hits.length, 0, report(hits, 'dead internal links'));
});

