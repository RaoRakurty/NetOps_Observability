// voice.test.js — the mechanical half of docs-portal/STYLE.md.
//
// STYLE.md is the prose rulebook; this file enforces the parts a machine can
// check, so a page that reads like a language model wrote it cannot merge.
// Run it with `npm test` in docs-portal (node:test, no new dependencies).
//
// Every rule here exists because a real vendor documentation set (Fortinet,
// Palo Alto Networks, CrowdStrike) does not break it. When a rule fires, fix
// the prose — do not widen the rule. Adding an allowance is a STYLE.md change.

const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const DOCS = path.join(__dirname, '..', 'docs');

// ── page collection ─────────────────────────────────────────────────────────

function walk(dir, out = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (entry.name.endsWith('.md') || entry.name.endsWith('.mdx')) out.push(full);
  }
  return out;
}

function parse(file) {
  const raw = fs.readFileSync(file, 'utf8');
  const m = raw.match(/^---\n([\s\S]*?)\n---\n?/);
  const front = {};
  if (m) {
    for (const line of m[1].split('\n')) {
      const kv = line.match(/^([a-z_]+):\s*(.*)$/);
      if (kv) front[kv[1]] = kv[2].replace(/^['"]|['"]$/g, '').trim();
    }
  }
  const body = m ? raw.slice(m[0].length) : raw;
  const offset = m ? raw.slice(0, m[0].length).split('\n').length - 1 : 0;
  return { file, raw, front, body, offset, rel: path.relative(DOCS, file) };
}

const PAGES = walk(DOCS).map(parse);

// A generated page quotes the source verbatim: alert-rule summaries, route
// summaries, error strings. Rewriting a quotation to satisfy a house rule
// would make it a lie, so generated pages are exempt from the rules that
// govern prose. They are NOT exempt from front matter, links or placeholders.
const GENERATED = /GENERATED by docs-portal\/scripts\//;
const AUTHORED = PAGES.filter(p => !GENERATED.test(p.raw));

// Prose only: strip fenced code, inline code, HTML comments, link targets and
// front matter, so a rule never fires on a command, an identifier, or a URL.
function prose(page) {
  return page.body
    .replace(/```[\s\S]*?```/g, '\n')
    .replace(/^ {4}.*$/gm, '')
    .replace(/`[^`]*`/g, ' ')
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/\]\([^)]*\)/g, '] ')
    .replace(/^\s*import .*$/gm, '');
}

function lineOf(page, index) {
  return page.raw.slice(0, index).split('\n').length;
}

// The cap keeps a normal failure readable. Set VOICE_FULL=1 to print every hit
// when you are working through a backlog.
const CAP = process.env.VOICE_FULL ? Infinity : 40;

function report(hits, what) {
  const lines = hits.slice(0, CAP).map(h => `  ${h.rel}:${h.line}  ${h.detail}`);
  const more = hits.length > CAP ? `\n  … and ${hits.length - CAP} more` : '';
  return `${hits.length} ${what}\n${lines.join('\n')}${more}`;
}

// ── 1. the AI-tell denylist ─────────────────────────────────────────────────

// Words and phrases that mark machine-written marketing prose. None of them
// appear in a Fortinet, Palo Alto or CrowdStrike administration guide.
const DENY = [
  // filler adjectives
  [/\brobust\b/gi, 'say what it actually does'],
  [/\bseamless(ly)?\b/gi, 'name the thing that does not require work'],
  [/\bcomprehensive\b/gi, 'say what is covered'],
  [/\bpowerful\b/gi, 'say what it does'],
  [/\bintuitive\b/gi, 'show the procedure instead'],
  [/\brich\b(?=\s+(set|data|history|context))/gi, 'say how much'],
  [/\bcutting[- ]edge\b/gi, 'drop it'],
  [/\bstate[- ]of[- ]the[- ]art\b/gi, 'drop it'],
  [/\bbest[- ]in[- ]class\b/gi, 'drop it'],
  [/\bworld[- ]class\b/gi, 'drop it'],
  [/\bunparalleled\b/gi, 'drop it'],
  [/\bgame[- ]chang\w*/gi, 'drop it'],
  [/\brevolutionary\b/gi, 'drop it'],
  [/\beffortless(ly)?\b/gi, 'drop it'],
  [/\bturnkey\b/gi, 'drop it'],
  // filler verbs
  [/\bleverage[sd]?\b/gi, 'use "use"'],
  [/\bdelv(e|es|ing)\b/gi, 'use "read" or "open"'],
  [/\bempower(s|ed|ing)?\b/gi, 'say what the reader can now do'],
  [/\bstreamline[sd]?\b/gi, 'say which step disappears'],
  [/\bsupercharge[sd]?\b/gi, 'drop it'],
  [/\bunlocks?\s+(the\s+|your\s+)?(full\s+|real\s+|true\s+)?(power|potential|value|insight)/gi, 'say what becomes available'],
  [/\belevat(e|es|ing)\b/gi, 'drop it'],
  [/\bharness(es|ing)?\b/gi, 'use "use"'],
  [/\bfoster(s|ing)?\b/gi, 'drop it'],
  [/\bnavigat\w+ the complexit\w+/gi, 'drop it'],
  // filler connectives and hedges
  [/\bit'?s worth noting\b/gi, 'state the fact'],
  [/\bit'?s important to note\b/gi, 'state the fact'],
  [/\bplease note that\b/gi, 'state the fact'],
  [/\bin today'?s\b/gi, 'drop it'],
  [/\bfast[- ]paced\b/gi, 'drop it'],
  [/\bever[- ](evolving|changing)\b/gi, 'drop it'],
  [/\bat the end of the day\b/gi, 'drop it'],
  [/\bin conclusion\b/gi, 'drop it'],
  [/\bmoreover\b/gi, 'start a new sentence'],
  [/\bfurthermore\b/gi, 'start a new sentence'],
  [/\badditionally,/gi, 'start a new sentence'],
  [/\bwhen it comes to\b/gi, 'name the subject'],
  [/\bthat being said\b/gi, 'drop it'],
  [/\bdive (in|into|deep)\b/gi, 'use "open" or "read"'],
  [/\bdeep dive\b/gi, 'use "detail"'],
  [/\bin the realm of\b/gi, 'drop it'],
  [/\ba myriad of\b/gi, 'say how many'],
  [/\ba plethora of\b/gi, 'say how many'],
  [/\btapestry\b/gi, 'drop it'],
  [/\bjourney\b(?!\s*(map|-))/gi, 'name the task'],
  [/\bis a testament to\b/gi, 'drop it'],
  [/\bwhether you'?re\b/gi, 'address one reader'],
  [/\bsimply\b/gi, 'drop it — nothing is simple to a reader who is stuck'],
  [/\beasily\b/gi, 'drop it'],
  [/\bjust\b(?=\s+(click|run|open|add|set|type|enter))/gi, 'drop it'],
  // the meta-voice opener: writing about the documentation instead of about
  // the product. The reader already knows they are on a page.
  [/\bthis (page|document|guide|section|article) (explains|describes|covers|shows|walks|provides|outlines|details)\b/gi,
   'open with the product or the reader, not with the page'],
  [/\bthe documentation (explains|describes|provides|covers)\b/gi, 'write in product voice'],
  [/\bin this (guide|article|section|document)\b/gi, 'drop it'],
  [/\bwill be (covered|discussed|explained)\b/gi, 'cover it or drop it'],
];

test('no AI-tell words or marketing filler', () => {
  const hits = [];
  for (const page of AUTHORED) {
    const text = prose(page);
    for (const [re, fix] of DENY) {
      for (const m of text.matchAll(re)) {
        hits.push({
          rel: page.rel,
          line: lineOf(page, page.raw.indexOf(m[0])),
          detail: `"${m[0]}" — ${fix}`,
        });
      }
    }
  }
  assert.equal(hits.length, 0, report(hits, 'banned phrases'));
});

// ── 2. second person, never first person plural ─────────────────────────────

test('addresses the reader as "you", never as "we"', () => {
  const hits = [];
  // The apostrophe is REQUIRED: an optional one turns this into a rule that
  // fires on "were" and "well".
  const FIRST = [/\bwe['\u2019](ll|ve|re|d)\b/gi, /\bwe\s/gi, /\bour\b/gi,
                 /\blet['\u2019]s\b/gi];
  for (const page of PAGES) {
    const text = prose(page);
    for (const re of FIRST) {
      for (const m of text.matchAll(re)) {
        hits.push({
          rel: page.rel,
          line: lineOf(page, page.raw.indexOf(m[0])),
          detail: `"${m[0].trim()}" — the documentation is not a person`,
        });
      }
    }
  }
  assert.equal(hits.length, 0, report(hits, 'first-person-plural uses'));
});

// ── 2b. product vocabulary ──────────────────────────────────────────────────

// The console says "observations", never "signals" — a vitest vocabulary
// scanner enforces it in the product, and the documentation matches. The
// exceptions are the engine's own terms: a skill's "chain signal" / "machine
// signal", and the `signal` evidence class (which is inline code and is
// stripped before this runs).
test('the product vocabulary is used', () => {
  const hits = [];
  const BANNED = [
    [/\bsignals?\b/gi, 'the product says "observations", not "signals"',
     /((chain|machine|correlation|evidence|no)\s+signals?|signals?\s+(selector|parameter|class))\b/i],
    [/\bthe NOC\b/g, 'name the seam and the party that owns it, not "the NOC"', null],
  ];
  for (const page of AUTHORED) {
    const text = prose(page);
    for (const [re, fix, allow] of BANNED) {
      for (const m of text.matchAll(re)) {
        // The window must reach BOTH ways: the qualifier can precede the word
        // ("chain signal") or follow it ("signal selector").
        const around = text.slice(Math.max(0, m.index - 24), m.index + m[0].length + 24);
        if (allow && allow.test(around)) continue;
        hits.push({
          rel: page.rel,
          line: lineOf(page, page.raw.indexOf(m[0])),
          detail: `"${m[0]}" — ${fix}`,
        });
      }
    }
  }
  assert.equal(hits.length, 0, report(hits, 'product-vocabulary problems'));
});

// ── 3. em-dash discipline ───────────────────────────────────────────────────

// One em dash can carry an aside. Three in a paragraph is the rhythm of
// generated prose. Vendor guides use commas, colons and full stops.
test('em dashes stay rare', () => {
  const hits = [];
  for (const page of PAGES) {
    // A bold span is a quoted product string — a console label such as
    // **OSPF — IGP health**. Quoting the product is not a prose habit, so its
    // punctuation does not count against the budget.
    // A bold span is a quoted product string and a heading is structure —
    // STYLE.md sanctions the `### Step 1 — …` form. Neither is prose rhythm,
    // so neither counts against the budget.
    const text = prose(page)
      .replace(/^\s*#+ .*$/gm, ' ')
      .replace(/^\s*\|.*$/gm, ' ')
      .replace(/\*\*[^*]*\*\*/g, ' ');
    const total = (text.match(/—/g) || []).length;
    const words = text.split(/\s+/).filter(Boolean).length;
    const budget = Math.max(3, Math.floor(words / 250));
    if (total > budget) {
      hits.push({
        rel: page.rel, line: 1,
        detail: `${total} em dashes in ${words} words (budget ${budget})`,
      });
    }
    for (const para of text.split(/\n\s*\n/)) {
      if ((para.match(/—/g) || []).length > 1) {
        hits.push({
          rel: page.rel,
          line: lineOf(page, page.raw.indexOf(para.trim().slice(0, 40))),
          detail: 'more than one em dash in a single paragraph',
        });
      }
    }
  }
  assert.equal(hits.length, 0, report(hits, 'em-dash problems'));
});

// ── 4. sentence length ──────────────────────────────────────────────────────

test('sentences stay under 45 words', () => {
  const hits = [];
  for (const page of AUTHORED) {
    const text = prose(page)
      .replace(/^\s*\|.*$/gm, '')      // tables
      .replace(/^\s*#+ .*$/gm, '');    // headings
    // Split on line breaks FIRST: a list item without a terminal full stop is
    // its own unit, not the opening clause of the next bullet.
    const units = text.split(/\n/).flatMap(line => line.split(/(?<=[.!?])\s+/));
    for (const sentence of units) {
      const words = sentence.trim().split(/\s+/).filter(Boolean);
      if (words.length > 45) {
        hits.push({
          rel: page.rel,
          line: lineOf(page, page.raw.indexOf(sentence.trim().slice(0, 40))),
          detail: `${words.length}-word sentence: "${words.slice(0, 8).join(' ')}…"`,
        });
      }
    }
  }
  assert.equal(hits.length, 0, report(hits, 'over-long sentences'));
});

