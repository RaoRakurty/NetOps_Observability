// report_test.go — the signed document.
//
// The GOLDEN TEST below is the load-bearing one. It pins the exact canonical
// bytes for a fixed document, so a future change to a struct tag, a field
// order, an encoder setting or a Go version that altered them would fail here
// rather than silently invalidating every report a customer already holds.

import (
	"crypto/ed25519"
	"encoding/json"
	"strings"
	"testing"
	"time"
)

// deterministicKey is a fixed ed25519 key derived from a constant seed. Tests
// need a stable signature; production never uses this path (ReportKey draws
// from crypto/rand).
func deterministicKey() ed25519.PrivateKey {
	seed := make([]byte, ed25519.SeedSize)
	for i := range seed {
		seed[i] = byte(i + 1)
	}
	return ed25519.NewKeyFromSeed(seed)
}

