def _load():
    spec = importlib.util.spec_from_file_location("correlix_sbom", SCRIPT)
    assert spec and spec.loader
    module = importlib.util.module_from_spec(spec)
    sys.modules["correlix_sbom"] = module
    spec.loader.exec_module(module)
    return module


