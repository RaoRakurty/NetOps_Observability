def test_provenance_is_keyed_to_the_dependency_inputs_not_head():
    """`inputs_revision()` must resolve to a commit that touched a manifest.

    If this ever falls back to HEAD, the committed SBOM starts churning on every
    unrelated commit and `--check` becomes noise.
    """
    rev = sbom.inputs_revision()
    if rev is None:
        pytest.skip("not a git checkout")
    sha, date = rev
    assert len(sha) == 40
    assert date.startswith("20")
    assert "deployment/docker" in sbom.INPUT_PATHS
    assert "src/backend/go.mod" in sbom.INPUT_PATHS


def test_source_date_epoch_overrides_the_timestamp(monkeypatch):
    monkeypatch.setenv("SOURCE_DATE_EPOCH", "1700000000")
    assert sbom.build_timestamp() == "2023-11-14T22:13:20Z"


