def test_committed_sbom_matches_the_current_dependency_tree():
    """`docs/sbom/` must be regenerated whenever a dependency moves.

    This test failing is not a bug in the test: it means a dependency changed and
    the committed bill of materials no longer describes the tree. Fix it with:

        python3 scripts/sbom.py
    """
    assert sbom.main(["--check"]) == 0, (
        "docs/sbom/ is stale — run `python3 scripts/sbom.py` and commit the result"
    )
