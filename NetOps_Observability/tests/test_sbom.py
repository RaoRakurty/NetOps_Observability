"""Unit tests for `scripts/sbom.py` — the committed CycloneDX bill of materials.

The SBOM is a RELEASE ARTIFACT: it is what a customer or an auditor is handed
when they ask what is inside the appliance, and it is the inventory the Trivy
scan is run against. A wrong SBOM is worse than no SBOM, because it is believed.

What is asserted, and why it matters:

  determinism        The document is COMMITTED. If it churned on every run, the
                     diff would be noise, nobody would read it, and a real
                     component change would slip through unnoticed. Two renders
                     of the same tree must be byte-identical, and the ordering
                     of the input must not reach the output.
  direct vs indirect `correlix:direct` is how the CLAUDE.md §6 allowlist stays
                     legible in the SBOM. Misreading `// indirect` would make an
                     unreviewed transitive module look like an allowlisted one.
  hash fidelity      npm `integrity` is base64 and pip `--hash=` is hex; both
                     become CycloneDX hex. Getting the decode wrong yields a
                     document full of confident, wrong digests.
  image ref parsing  `registry:5000/team/app:tag@sha256:...` — the port colon and
                     the tag colon are the same character. A parser that splits
                     on the wrong one silently mislabels the registry, and the
                     digest-pinned audit built on top of it becomes fiction.
  --check            The CI gate. It must fail on a stale OR missing file, never
                     rewrite anything while checking, and — the subtle half —
                     must compare the COMPONENT SET, not the metadata. A gate
                     that failed merely because the file was regenerated at a
                     different commit would be red constantly, and a gate that
                     is constantly red is a gate that gets ignored.
  stable provenance  The document is keyed to the last commit that touched a
                     DEPENDENCY INPUT, and image origins name `file(service)`
                     rather than `file:line`. Both exist because the first draft
                     churned on every unrelated commit and on every compose edit
                     that shifted a line number.
  the committed tree The last test asserts `docs/sbom/` matches the current
                     dependencies. It is DESIGNED to fail when you bump a
                     dependency without regenerating — that failure is the
                     feature, and the fix is `python3 scripts/sbom.py`.

Run:  python3 -m pytest tests/test_sbom.py -q
"""

