def test_render_emits_every_class_plus_the_aggregate():
    documents = sbom.render()
    expected = {f"{c}.cdx.json" for c in sbom.CLASSES} | {f"{sbom.AGGREGATE}.cdx.json"}
    assert set(documents) == expected


def test_aggregate_is_the_deduplicated_union_of_the_classes():
    documents = sbom.render()
    union = set()
    for class_name in sbom.CLASSES:
        union |= {
            c["bom-ref"] for c in json.loads(documents[f"{class_name}.cdx.json"])["components"]
        }
    aggregate = json.loads(documents[f"{sbom.AGGREGATE}.cdx.json"])["components"]
    refs = [c["bom-ref"] for c in aggregate]
    assert set(refs) == union
    assert len(refs) == len(set(refs)), "aggregate contains duplicate bom-refs"


